"""Generate firmware records and browser data from the supplied canonical JSON."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def generate(check=False):
    configs = {}
    for name in ('Default', 'Empty'):
        data = json.loads((ROOT / f'web/builtin/ChainPad-Configuration-{name}.json').read_text(encoding='utf-8'))
        if (data['format'], data['version'], data['schemaVersion']) != ('chainpad-configuration', 2, 2):
            raise ValueError('Unsupported builtin format')
        if [c['input'] for c in data['chains']] != list(range(28)):
            raise ValueError('Expected 28 ordered input chains')
        # Communication fields in the supplied files are intentionally excluded.
        configs[name] = {k: data[k] for k in ('format', 'version', 'schemaVersion', 'chains', 'encoderRotation')}
    compact = lambda data: json.dumps(data, ensure_ascii=True, separators=(',', ':'))
    default = configs['Default']
    header = '// Generated by scripts/builtin_config.py; edit web/builtin/*.json instead.\n#pragma once\nnamespace chimera { namespace builtin {\n'
    header += 'constexpr const char* chains[] = {\n'
    header += ''.join('R"BUILTIN(' + compact(c) + ')BUILTIN",\n' for c in default['chains'])
    header += '};\nconstexpr char rotation[] = R"BUILTIN(' + compact(default['encoderRotation']) + ')BUILTIN";\n}}\n'
    js = '// Generated by scripts/builtin_config.py; edit web/builtin/*.json instead.\nconst BuiltinConfigs = ' + compact(configs) + ';\n'
    for path, content in ((ROOT / 'src/builtin_config_data.h', header), (ROOT / 'web/builtin-config-data.js', js)):
        same = path.exists() and path.read_text(encoding='utf-8') == content
        if check and not same:
            raise RuntimeError(f'Stale generated builtin data: {path}')
        if not check and not same:
            path.write_text(content, encoding='utf-8')


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    generate(parser.parse_args().check)
